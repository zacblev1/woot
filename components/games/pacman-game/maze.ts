// Count pellets in maze
export function countPellets(maze: number[][]): number {
  let count = 0
  for (let y = 0; y < maze.length; y++) {
    for (let x = 0; x < maze[y].length; x++) {
      if (maze[y][x] === 1 || maze[y][x] === 2) {
        count++
      }
    }
  }
  return count
}

// Clone maze for new game
export function cloneMaze(): number[][] {
  return INITIAL_MAZE.map(row => [...row])
}
